import { chromium } from 'playwright';
const [port] = process.argv.slice(2);
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--disable-accelerated-2d-canvas'] });
const ctx = await b.newContext({ viewport: { width: 844, height: 390 }, deviceScaleFactor: 1 });
await ctx.addInitScript(() => { if (!sessionStorage.getItem('x')) { sessionStorage.setItem('x', '1'); localStorage.setItem('puffy.beaten', '6'); localStorage.setItem('puffy.rootbeer', '120'); localStorage.setItem('puffy.light', '1'); } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => m.type() === 'error' && errs.push('console: ' + m.text()));
await p.goto(`http://localhost:${port}/`);
await p.waitForFunction(() => window.game?.registry?.get('ready'), null, { timeout: 300000 });
const click = (sel) => p.evaluate((s) => document.querySelector(s)?.click(), sel);
const log = [];
const note = async (what) => log.push(`${what}: ${await p.evaluate(() => (document.querySelector('#ui .screen h2, #ui .screen h1')?.textContent ?? '-').slice(0, 30))}`);
await click('[data-act=shop]'); await p.waitForTimeout(1200); await note('shop');
for (const id of ['party', 'frogskins', 'board']) { await click(`[data-buy="${id}"]`); await p.waitForTimeout(1500); }
log.push(`after buying: left ${await p.evaluate(() => document.querySelector('.shop-count')?.textContent)} | owned ${await p.evaluate(() => localStorage.getItem('puffy.items'))} | wearing ${await p.evaluate(() => localStorage.getItem('puffy.wear'))}`);
await click('[data-off="board"]'); await p.waitForTimeout(800);
log.push(`after taking the board off: wearing ${await p.evaluate(() => localStorage.getItem('puffy.wear'))}`);
await p.keyboard.press('Escape'); await click('.shop-back, [data-act=back]'); await p.waitForTimeout(1200); await note('back from shop');
await click('[data-act=battle]'); await p.waitForTimeout(800); await note('battle code');
await click('.battle-code [data-act=go]'); await p.waitForTimeout(3000); await note('lobby');
await click('.bl-back'); await p.waitForTimeout(1500); await note('back from lobby');
await click('[data-act=bosses]'); await p.waitForTimeout(800); await note('bosses');
await click('[data-act=back]'); await p.waitForTimeout(800); await note('back from bosses');
await click('[data-act=account]'); await p.waitForTimeout(800); await note('account');
console.log(log.join('\n'));
console.log('errors:', JSON.stringify(errs.slice(0, 6)));
await b.close();
