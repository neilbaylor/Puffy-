// usage: node start.mjs <port> <part> [throttle]  -> Play -> level ready: time and top self-time functions
import { chromium } from 'playwright';
const [port, part = '2', thr = '4'] = process.argv.slice(2);
const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--disable-accelerated-2d-canvas'] });
const ctx = await b.newContext({ viewport: { width: 844, height: 390 }, deviceScaleFactor: 1 });
await ctx.addInitScript(() => { localStorage.setItem('puffy.beaten', '6'); localStorage.setItem('puffy.dev', '1'); localStorage.setItem('puffy.light', '0'); localStorage.setItem('puffy.lightRetried', '1'); });
const p = await ctx.newPage();
const cdp = await ctx.newCDPSession(p);
await p.goto(`http://localhost:${port}/`);
await p.waitForFunction(() => window.game?.registry?.get('ready'), null, { timeout: 600000 });
await p.evaluate((n) => { const el = document.querySelector(`.lvl[data-lvl="${n}"]`); el?.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true })); el?.click(); }, part);
await p.waitForTimeout(4000);
await cdp.send('Emulation.setCPUThrottlingRate', { rate: Number(thr) });
await cdp.send('Profiler.enable');
await cdp.send('Profiler.setSamplingInterval', { interval: 250 });
await cdp.send('Profiler.start');
const t1 = Date.now();
await p.click('[data-act=play]');
await p.waitForFunction(() => window.game.scene.isActive('Game') && window.game.scene.getScene('Game').players?.[0]?.body, null, { timeout: 300000, polling: 50 });
const startMs = Date.now() - t1;
const { profile } = await cdp.send('Profiler.stop');
const self = new Map(); const byId = new Map(profile.nodes.map((n) => [n.id, n])); let total = 0;
profile.samples.forEach((s, i) => { const cf = byId.get(s).callFrame; const key = `${cf.functionName || '(anon)'} ${(cf.url.split('/').pop() || '').slice(0, 24)}:${cf.lineNumber}`; self.set(key, (self.get(key) || 0) + profile.timeDeltas[i]); total += profile.timeDeltas[i]; });
console.log(JSON.stringify({ part, thr, startMs }));
console.log([...self.entries()].sort((x, y) => y[1] - x[1]).slice(0, Number(process.env.TOP || 20)).map(([k, v]) => `${((100 * v) / total).toFixed(1).padStart(5)}%  ${(v / 1000).toFixed(0).padStart(5)} ms  ${k}`).join('\n'));
await b.close();
